using System.Text;
using FireURQ.Porter.AST;
using FireURQ.Porter.Analysis;

namespace FireURQ.Porter.Translation;

public sealed class ProjectTranslator
{
    private readonly CSharpDeclarationTranslator _declarationTranslator =
        new();

    private readonly DelphiToCSharpTranslator _functionTranslator =
        new();

    public IReadOnlyList<TranslationResult> Translate(
        IReadOnlyList<ProjectTranslationInput> inputs,
        string outputDirectory)
    {
        Directory.CreateDirectory(outputDirectory);

        var results =
            new List<TranslationResult>();

        foreach (ProjectTranslationInput input in inputs)
        {
            results.Add(
                TranslateUnit(
                    input,
                    outputDirectory));
        }

        return results;
    }

    private TranslationResult TranslateUnit(
        ProjectTranslationInput input,
        string outputDirectory)
    {
        string rootName =
            new DirectoryInfo(input.RootPath).Name;

        string relativePath =
            Path.GetRelativePath(
                input.RootPath,
                input.FilePath);

        string outputRelativePath =
            Path.ChangeExtension(
                relativePath,
                ".cs");

        string outputFile =
            Path.Combine(
                outputDirectory,
                rootName,
                outputRelativePath);

        try
        {
            string? outputParent =
                Path.GetDirectoryName(outputFile);

            if (!string.IsNullOrWhiteSpace(outputParent))
                Directory.CreateDirectory(outputParent);

            var builder =
                new StringBuilder();

            builder.AppendLine("// <auto-generated />");
            builder.AppendLine($"// Source: {input.FilePath}");
            builder.AppendLine();
            builder.AppendLine("using System;");
            builder.AppendLine("using System.Collections.Generic;");
            builder.AppendLine();

            string declarations =
                _declarationTranslator.Translate(
                    input.SemanticModel);

            if (!string.IsNullOrWhiteSpace(declarations))
            {
                builder.AppendLine(declarations);
            }

            int functionsTranslated = 0;

            foreach (
                (
                    BodyTokenAnalyzer.BodyInfo Body,
                    BehaviorAnalyzer.BehaviorInfo Behavior)
                body in input.Bodies)
            {
                if (body.Body.BodyTokens.Count == 0)
                    continue;

                SemanticFunction? function =
                    MatchFunction(
                        input.Unit,
                        body.Body,
                        input.SemanticModel);

                if (function is null)
                {
                    builder.AppendLine(
                        $"// TODO: Unmatched Delphi implementation: " +
                        $"{body.Body.Name}");

                    builder.AppendLine();
                    continue;
                }

                string translated =
                    _functionTranslator.TranslateFunction(
                        function,
                        body.Behavior);

                builder.AppendLine(translated);
                builder.AppendLine();

                functionsTranslated++;
            }

            string outputText =
                builder.ToString();

            File.WriteAllText(
                outputFile,
                outputText,
                Encoding.UTF8);

            int todoCount =
                CountTodos(outputText);

            return new TranslationResult(
                input.FilePath,
                outputFile,
                true,
                functionsTranslated,
                todoCount,
                null);
        }
        catch (Exception ex)
        {
            return new TranslationResult(
                input.FilePath,
                outputFile,
                false,
                0,
                0,
                ex.ToString());
        }
    }

private static SemanticFunction? MatchFunction(
    DelphiUnit unit,
    BodyTokenAnalyzer.BodyInfo body,
    SemanticUnit semanticUnit)
{
    return FunctionImplementationMatcher.Match(
        unit,
        body,
        semanticUnit);
}

    private static int CountTodos(
        string text)
    {
        return text
            .Split(
                '\r',
                '\n')
            .Count(
                line =>
                    line.Contains(
                        "TODO:",
                        StringComparison.OrdinalIgnoreCase));
    }
}

public sealed record ProjectTranslationInput(
    string RootPath,
    string FilePath,
    DelphiUnit Unit,
    SemanticUnit SemanticModel,
    IReadOnlyList<(
        BodyTokenAnalyzer.BodyInfo Body,
        BehaviorAnalyzer.BehaviorInfo Behavior)> Bodies
);
